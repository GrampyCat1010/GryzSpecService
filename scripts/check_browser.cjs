// Local browser smoke test. Set NODE_PATH to the directory containing Playwright.
const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
async function main(){
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 const output=path.join(root,'.impeccable','review');fs.mkdirSync(output,{recursive:true});
 await page.goto('http://127.0.0.1:8000/',{waitUntil:'networkidle'});
 await page.locator('#service-picker button').first().waitFor({state:'attached'});
 await page.screenshot({path:path.join(output,'desktop.png'),fullPage:true});
 console.log('HOME',JSON.stringify({title:await page.title(),nav:await page.locator('.navigation button').count(),overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),errors}));
 await page.getByRole('button',{name:'Нужна помощь в дороге',exact:true}).click();
 await page.waitForTimeout(600);
 await page.screenshot({path:path.join(output,'desktop-form.png'),fullPage:true});
 const form=page.locator('#personal-form');
 await form.locator('[name=brand]').fill('КАМАЗ');
 await form.locator('[name=model]').fill('5490');
 await form.locator('[name=description]').fill('Проверка сайта: неисправность двигателя');
 await form.locator('[name=address]').fill('Трасса М5, 320 км');
 await form.locator('[name=name]').fill('Тестовый клиент');
 await form.locator('[name=phone]').fill('89991234567');
 await form.locator('[name=consent]').check();
 await form.locator('[type=submit]').click();
 await page.locator('#success-dialog[open]').waitFor();
 console.log('ORDER',JSON.stringify({message:await page.locator('#success-message').innerText(),phone:await form.locator('[name=phone]').inputValue()}));
 await page.locator('#success-dialog [data-close-dialog]').last().click();
 await page.locator('[data-chat]').click();
 await page.screenshot({path:path.join(output,'desktop-chat.png'),fullPage:true});
 await page.locator('#chat-input').fill('Как вызвать помощь?');
 await page.locator('#chat-form button').click();
 await page.locator('.message:not(.user)').filter({hasText:'Я помогу'}).waitFor();
 await page.locator('[data-close-chat]').click();
 await page.locator('[data-chat]').click();
 console.log('CHAT_RESET',await page.locator('.message').count());
 await page.locator('[data-close-chat]').click();
 await page.locator('.navigation [data-view=settings]').click();
 await page.locator('[data-theme-choice=dark]').click();
 await page.screenshot({path:path.join(output,'desktop-dark.png'),fullPage:true});
 await page.locator('[data-theme-choice=night]').click();
 await page.screenshot({path:path.join(output,'desktop-night.png'),fullPage:true});
 await page.locator('[data-theme-choice=light]').click();
 await page.setViewportSize({width:390,height:844});
 await page.locator('.wordmark').click();
 await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
 await page.locator('.navigation [data-view=personal]').click();
 await page.screenshot({path:path.join(output,'mobile-form.png'),fullPage:true});
 console.log('MOBILE',JSON.stringify({overflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),errors}));
 await page.locator('[data-chat]').click();
 await page.screenshot({path:path.join(output,'mobile-chat.png'),fullPage:true});
 await page.locator('[data-close-chat]').click();
 for(const width of [320,768,1024,1920]){await page.setViewportSize({width,height:900});for(const view of ['home','personal','corporate','services','settings']){if(view==='home')await page.locator('.wordmark').click();else await page.locator(`.navigation [data-view=${view}]`).click();if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Overflow '+width+' '+view);if(width===320&&view==='home')await page.screenshot({path:path.join(output,'mobile-320.png'),fullPage:true});}}
 console.log('RESPONSIVE_OK widths=320,390,768,1024,1440,1920; views=5; errors='+JSON.stringify(errors));
 await browser.close();
 if(errors.length)process.exitCode=1;
}
main().catch(e=>{console.error(e.message);process.exit(1)});
